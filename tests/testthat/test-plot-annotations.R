test_that("with 3 sites the captions say that the common mean has no posterior mean", {
  fit <- reliability_posterior(c(-1, 0, 1), se = c(.5, 1, 1.5))
  p <- plot_pooling(fit)
  expect_silent(ggplot2::ggplot_build(p))
  expect_false(any(vapply(p$layers, function(layer) inherits(layer$geom, "GeomVline"), FALSE)))
  caption <- plain_plot_caption(p$labels$caption)
  expect_match(caption, "average conditional predictions", fixed = TRUE)
  expect_match(caption, "common mean has no posterior mean", fixed = TRUE)
  expect_false(grepl("predicted value from the mean model", caption, fixed = TRUE))
  density <- plot_functionals(fit)
  expect_false(grepl("dashed line", plain_plot_caption(density$labels$caption), fixed = TRUE))
  expect_identical(sum(vapply(density$layers, function(layer) inherits(layer$geom, "GeomSegment"), FALSE)), 1L)
  dashboard <- plot_dashboard(fit)
  expect_silent(patchwork::patchworkGrob(dashboard))
  caption <- plain_plot_caption(dashboard$patches$annotation$caption)
  expect_match(caption, "common mean has no posterior mean", fixed = TRUE)
  expect_false(grepl("vertical line is the mean effect", caption, fixed = TRUE))
  expect_false(grepl("dashed, the value", caption, fixed = TRUE))
})
