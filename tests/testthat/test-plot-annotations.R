test_that("the dashboard says that the density axis is cut only when it is", {
  fit <- reliability_posterior(estimate, se = se, data = eight_schools)
  density <- plot_functionals(fit)
  display <- attr(density, ".rp_density_display")
  expect_true(display$cut)
  expect_true(display$exact)
  expect_identical(display$which, "I")
  expect_gt(max(density$data$density), density$coordinates$limits$y[[2]])
  dashboard <- plot_dashboard(fit)
  caption <- plain_plot_caption(dashboard$patches$annotation$caption)
  expect_match(caption, "(c) Posterior density of I", fixed = TRUE)
  expect_match(caption, "The density grows without bound near I = 0, and its vertical axis is cut there.", fixed = TRUE)
  expect_identical(lengths(regmatches(caption, gregexpr("(c)", caption, fixed = TRUE))), 1L)
  other <- reliability_posterior(20 * seq(-2, 2, length.out = 8), se = rep(1, 8))
  expect_false(attr(plot_functionals(other), ".rp_density_display")$cut)
  caption <- plain_plot_caption(plot_dashboard(other)$patches$annotation$caption)
  expect_false(grepl("vertical axis is cut", caption, fixed = TRUE))
})

test_that("a cut density of draws is described as cut, in panel (b) of the dashboard", {
  draws <- reliability_draws(c(rep(.001, 1980), rep(10, 20)), se2 = c(.001, .02, 1, 20, 100))
  density <- plot_functionals(draws)
  expect_true(attr(density, ".rp_density_display")$cut)
  expect_false(attr(density, ".rp_density_display")$exact)
  caption <- plain_plot_caption(density$labels$caption)
  expect_match(caption, "vertical axis is cut", fixed = TRUE)
  expect_false(grepl("grows without bound", caption, fixed = TRUE))
  caption <- plain_plot_caption(plot_dashboard(draws)$patches$annotation$caption)
  expect_match(caption, "(b) Posterior density of I", fixed = TRUE)
  expect_match(caption, "The vertical axis is cut to show the body of the density.", fixed = TRUE)
  expect_false(grepl("grows without bound", caption, fixed = TRUE))
})

