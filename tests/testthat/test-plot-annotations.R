plain_plot_caption <- function(x) gsub("[[:space:]]+", " ", x)

test_that("concentration captions distinguish averaged shares from averaged counts", {
  v <- c(.001, .02, 1, 20, 100)
  draws <- reliability_draws(rep(c(.001, 10), each = 1000), se2 = v)
  tab <- site_table(draws)
  count <- profile_summary(draws)$mean[profile_summary(draws)$quantity == "J_eff"]
  expect_gt(abs(count - 1 / sum(tab$share^2)), .1)
  p <- plot_concentration(draws, label_top = 0)
  caption <- plain_plot_caption(p$labels$caption)
  expect_match(caption, "posterior mean of the proportion", fixed = TRUE)
  expect_match(caption, "in general differs from", fixed = TRUE)
  expect_equal(diff(p$data$share), sort(tab$share, decreasing = TRUE), ignore_attr = TRUE)
  expect_equal(p$layers[[3]]$data$jeff, count)
  fixed <- reliability_profile(se2 = v, sigma_tau = 1)
  caption <- plain_plot_caption(plot_concentration(fixed)$labels$caption)
  expect_match(caption, "inverse of the sum of the squared proportions", fixed = TRUE)
  expect_false(grepl("in general differs", caption, fixed = TRUE))
  comparison <- compare_profiles(fixed = fixed, draws = draws)
  caption <- plain_plot_caption(plot_concentration(comparison)$labels$caption)
  expect_match(caption, "For posterior fits and draws", fixed = TRUE)
  expect_match(caption, "For fixed profiles and designs", fixed = TRUE)
})

